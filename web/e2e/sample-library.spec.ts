async function login(request:any){const status=await(await request.get('/api/status')).json();await request.post(`/api/${status.bootstrap?'register':'login'}`,{headers,data:{username:'browser-test',password:'test1234'}})}
async function upload(request:any,project:string,buffer:Buffer,name:string){const result=await request.post(`/api/projects/${project}/samples`,{headers,multipart:{sample:{name,mimeType:'application/octet-stream',buffer}}});expect(result.ok(),await result.text()).toBe(true);return result.json()}
test('sample imports preserve channels and project members can use another author’s private sample',async({request,playwright})=>{
  await login(request)
  const p=await(await request.post('/api/projects',{headers,data:{name:'Shared samples',mode:'freeform'}})).json()
  const token=(await(await request.post(`/api/projects/${p.id}/invite`,{headers,data:{role:'editor'}})).json()).token
  const author=await playwright.request.newContext({baseURL:'http://127.0.0.1:3101'})
  expect((await author.post('/api/register',{headers,data:{username:'sample-author',password:'test1234',invite:token}})).ok()).toBe(true)
  expect((await author.post('/api/join',{headers,data:{token}})).ok()).toBe(true)
  const sample=await upload(author,p.id,audio('flac',6),'surround.flac')
  expect(sample.channels).toBe(6);expect(sample.global).toBe(false)
  const projectSamples=await(await request.get(`/api/projects/${p.id}/samples`)).json();expect(projectSamples.some((s:any)=>s.id===sample.id)).toBe(true)
  const ownLibrary=await(await request.get(`/api/projects/${p.id}/sample-library`)).json();expect(ownLibrary.some((s:any)=>s.id===sample.id)).toBe(false)
  expect((await request.get(`/api/projects/${p.id}/samples/${sample.id}/audio`)).ok()).toBe(true)
  expect((await request.put(`/api/projects/${p.id}/samples/${sample.id}`,{headers,data:{...sample,global:true}})).status()).toBe(403)
  const shared=await author.put(`/api/projects/${p.id}/samples/${sample.id}`,{headers,data:{...sample,global:true,tags:'surround, space',category:'Textures'}});expect(shared.ok()).toBe(true)
  let metadata=await shared.json()
  expect((await author.put(`/api/projects/${p.id}/samples/${sample.id}`,{headers,data:{...sample,global:true}})).status()).toBe(409)
  const other=await(await request.post('/api/projects',{headers,data:{name:'Sample destination',mode:'freeform'}})).json()
  expect((await(await request.get(`/api/projects/${other.id}/samples`)).json()).length).toBe(0)
  expect((await(await request.get(`/api/projects/${other.id}/sample-library`)).json()).some((s:any)=>s.id===sample.id)).toBe(true)
  const added=await request.post(`/api/projects/${other.id}/samples/${sample.id}/add`,{headers,data:{}});expect(added.ok()).toBe(true)
  expect((await added.json()).asset).toBeGreaterThan(0)
  metadata=await(await author.put(`/api/projects/${p.id}/samples/${sample.id}`,{headers,data:{...metadata,global:false}})).json()
  expect((await request.get(`/api/projects/${other.id}/samples/${sample.id}/audio`)).ok()).toBe(true)
  const fresh=await(await request.post('/api/projects',{headers,data:{name:'No private access',mode:'freeform'}})).json()
  expect((await request.get(`/api/projects/${fresh.id}/samples/${sample.id}/audio`)).ok()).toBe(false)
  expect((await request.post(`/api/projects/${fresh.id}/samples/${sample.id}/add`,{headers,data:{}})).ok()).toBe(false)
  const mp3=await upload(request,other.id,audio('mp3'),'tone.mp3');expect(mp3.channels).toBe(2)
  const aiff=await upload(request,other.id,audio('aiff',1),'tone.aiff');expect(aiff.channels).toBe(1)
  const m4a=await upload(request,other.id,audio('mp4'),'tone.m4a');expect(m4a.channels).toBe(2)
  const wav=await(await request.get(`/api/projects/${other.id}/samples/${mp3.id}/audio`)).body();expect(wav.subarray(0,4).toString()).toBe('RIFF')
  const fmt=wav.indexOf(Buffer.from('fmt '))+8;expect(wav.readUInt16LE(fmt+14)).toBe(32);expect(wav.readUInt32LE(fmt+4)).toBe(mp3.sample_rate)
  const bad=await request.post(`/api/projects/${other.id}/samples`,{headers,multipart:{sample:{name:'bad.mp3',mimeType:'audio/mpeg',buffer:Buffer.from('not audio')}}});expect(bad.status()).toBe(400)
  const playlist=await request.post(`/api/projects/${other.id}/samples`,{headers,multipart:{sample:{name:'unsafe.ffconcat',mimeType:'text/plain',buffer:Buffer.from("ffconcat version 1.0\nfile '/etc/passwd'\n")}}});expect(playlist.status()).toBe(400)
  await author.dispose()
})
