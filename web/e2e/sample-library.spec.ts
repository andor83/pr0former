function audio(format:string,channels=2){const dir=mkdtempSync(join(tmpdir(),'pr0-audio-fixture-'));try{const file=join(dir,'audio');const r=spawnSync('ffmpeg',['-hide_banner','-loglevel','error','-f','lavfi','-i','sine=frequency=440:sample_rate=44100','-t','1','-ac',String(channels),'-f',format,file]);if(r.status!==0)throw new Error(String(r.stderr));return readFileSync(file)}finally{rmSync(dir,{recursive:true,force:true})}}

